import sys
import os
import json

def encode_delta(num):
    """Encodes an unsigned integer into delta encoding format."""
    bytes_list = []
    while True:
        byte = num & 0x7f
        num >>= 7
        if num:
            byte |= 0x80
        bytes_list.append(byte)
        if not num:
            break
    return bytes(bytes_list)

def write_aiger(aiger_data, output_file):
    """Writes the AIGER format file from JSON data."""
    try:
        with open(output_file, 'wb') as f:
            # Write header
            header = f"aig {aiger_data['header']['M']} {aiger_data['header']['I']} {aiger_data['header']['L']} {aiger_data['header']['O']} {aiger_data['header']['A']}\n"
            f.write(header.encode('ascii'))
            
            # Write outputs
            for output in aiger_data['outputs']:
                lit = output['literal']  # Changed from 'input' to 'literal'
                f.write(f"{lit}\n".encode('ascii'))
            
            # Write AND gates
            for gate in sorted(aiger_data['ands'], key=lambda x: x['id']):
                # Get input literals with proper polarity
                rhs0, rhs1 = gate['inputs']
                lit0 = rhs0['id']
                # if rhs0['inverted']:
                #     lit0 ^= 1
                lit1 = rhs1['id']
                # if rhs1['inverted']:
                #     lit1 ^= 1
                
                # Sort inputs (required by AIGER format)
                if lit0 > lit1:
                    lit0, lit1 = lit1, lit0
                
                # Calculate and write deltas
                lhs = gate['id']
                delta0 = lhs - lit1
                delta1 = lit1 - lit0
                
                f.write(encode_delta(delta0))
                f.write(encode_delta(delta1))
            
            # Write symbol table
            for input_node in sorted(aiger_data['inputs'], key=lambda x: x['id']):
                if input_node['name']:
                    idx = (input_node['id'] // 2) - 1
                    f.write(f"i{idx} {input_node['name']}\n".encode('ascii'))
            
            for i, output in enumerate(aiger_data['outputs']):
                if output['name']:
                    f.write(f"o{i} {output['name']}\n".encode('ascii'))
            
            # Write comment
            f.write(b"c\n")
            f.write(b"This file was generated by aiger_json_to_aig.py\n")
            
    except Exception as e:
        print(f"Error writing AIGER file: {e}")
        return False
    
    return True

def main():
    if len(sys.argv) != 2:
        print("Usage: python aiger_json2aig.py <path_to_json_file>")
        return
    
    json_file = sys.argv[1]
    if not os.path.exists(json_file):
        print(f"Error: File {json_file} not found")
        return
    
    try:
        with open(json_file, 'r') as f:
            aiger_data = json.load(f)
    except Exception as e:
        print(f"Error reading JSON file: {e}")
        return
    
    output_file = os.path.splitext(json_file)[0] + '_.aig'
    if write_aiger(aiger_data, output_file):
        print(f"Successfully converted {json_file} to {output_file}")
    else:
        print(f"Failed to convert {json_file} to AIGER format")

if __name__ == "__main__":
    main()